-- Referral program ("Zaproś znajomego").
-- Additive. Every account gets one short code (created lazily from the app).
-- A new account opened from that link is recorded once (one referrer per account,
-- never yourself, only fresh accounts). When the referred account has a confirmed
-- e-mail AND a first READY take, both accounts get a take pack: 10 units in
-- public.studio_quota_credits (the same balance and insert path as grant_p24_quota_pack).
-- Max 10 rewarded referrals per referrer per calendar month (Europe/Warsaw);
-- the rest stay pending and are paid in a later month.
-- Users may read their own rows (as referrer). Writes are service_role only.
-- This file is not applied from the app. Apply it with the normal migration path.

create table public.referral_codes (
  user_id uuid primary key references auth.users (id) on delete cascade,
  code text not null,
  created_at timestamptz not null default now(),
  constraint referral_codes_code_key unique (code),
  -- 8 characters of RFC 4648 base32 (A–Z, 2–7). Mirrors src/lib/referrals/referral-policy.ts.
  constraint referral_codes_code_chk check (code ~ '^[A-Z2-7]{8}$')
);

alter table public.referral_codes enable row level security;

drop policy if exists referral_codes_select_own on public.referral_codes;
create policy referral_codes_select_own
  on public.referral_codes
  for select
  to authenticated
  using (user_id = (select auth.uid()));

revoke all on public.referral_codes from anon, authenticated;
grant select on public.referral_codes to authenticated;
grant select, insert, update, delete on public.referral_codes to service_role;

comment on table public.referral_codes is
  'One referral code per account (lazy). SELECT own row. Mutations service_role only.';

create table public.referrals (
  id uuid primary key default gen_random_uuid(),
  referrer_id uuid not null references auth.users (id) on delete cascade,
  referred_id uuid not null references auth.users (id) on delete cascade,
  code text not null,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  rewarded_at timestamptz,
  referrer_notified_at timestamptz,
  -- One referrer per account.
  constraint referrals_referred_key unique (referred_id),
  constraint referrals_not_self_chk check (referrer_id <> referred_id),
  constraint referrals_status_chk check (status in ('pending', 'rewarded', 'revoked')),
  constraint referrals_rewarded_chk check ((status = 'rewarded') = (rewarded_at is not null) or status = 'revoked')
);

create index referrals_referrer_idx on public.referrals (referrer_id, rewarded_at);
create index referrals_pending_idx on public.referrals (created_at) where status = 'pending';

alter table public.referrals enable row level security;

drop policy if exists referrals_select_own_referrer on public.referrals;
create policy referrals_select_own_referrer
  on public.referrals
  for select
  to authenticated
  using (referrer_id = (select auth.uid()));

revoke all on public.referrals from anon, authenticated;
grant select on public.referrals to authenticated;
grant select, insert, update, delete on public.referrals to service_role;

comment on table public.referrals is
  'Referral program: who invited whom and when it was rewarded. SELECT own rows as referrer. Mutations service_role only.';

-- Lazy code: keep the existing code, else store the candidate generated by the app.
-- Returns the account code, or null when the candidate collided with another account
-- (the app retries with a new candidate).
create or replace function public.ensure_referral_code(p_user_id uuid, p_candidate text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'REFERRAL_FORBIDDEN' using errcode = '42501';
  end if;
  if p_user_id is null then
    return null;
  end if;

  select code into v_code from public.referral_codes where user_id = p_user_id;
  if v_code is not null then
    return v_code;
  end if;

  if p_candidate is null or p_candidate !~ '^[A-Z2-7]{8}$' then
    return null;
  end if;

  begin
    insert into public.referral_codes (user_id, code)
    values (p_user_id, p_candidate)
    on conflict (user_id) do nothing;
  exception
    when unique_violation then
      -- The candidate code belongs to someone else.
      return null;
  end;

  select code into v_code from public.referral_codes where user_id = p_user_id;
  return v_code;
end;
$$;

revoke all on function public.ensure_referral_code(uuid, text) from public, anon, authenticated;
grant execute on function public.ensure_referral_code(uuid, text) to service_role;

-- Record "account p_referred_id was opened from code p_code". Idempotent.
-- Results: recorded | already | unknown_code | self | unknown_user | too_old.
-- too_old: the account existed before the code, or is older than 7 days
-- (an existing account cannot attach a referrer later).
create or replace function public.record_referral(p_referred_id uuid, p_code text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text := upper(btrim(coalesce(p_code, '')));
  v_referrer uuid;
  v_code_created timestamptz;
  v_user_created timestamptz;
  v_id uuid;
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'REFERRAL_FORBIDDEN' using errcode = '42501';
  end if;
  if p_referred_id is null or v_code !~ '^[A-Z2-7]{8}$' then
    return 'unknown_code';
  end if;

  select user_id, created_at into v_referrer, v_code_created
  from public.referral_codes
  where code = v_code;
  if v_referrer is null then
    return 'unknown_code';
  end if;
  if v_referrer = p_referred_id then
    return 'self';
  end if;

  select created_at into v_user_created from auth.users where id = p_referred_id;
  if v_user_created is null then
    return 'unknown_user';
  end if;
  if v_user_created < v_code_created or v_user_created < now() - interval '7 days' then
    return 'too_old';
  end if;

  insert into public.referrals (referrer_id, referred_id, code)
  values (v_referrer, p_referred_id, v_code)
  on conflict (referred_id) do nothing
  returning id into v_id;

  return case when v_id is null then 'already' else 'recorded' end;
end;
$$;

revoke all on function public.record_referral(uuid, text) from public, anon, authenticated;
grant execute on function public.record_referral(uuid, text) to service_role;

-- Reward a pending referral of account p_referred_id. Atomic and idempotent:
-- both packs are added in one transaction, a second call finds status 'rewarded'.
-- Results (jsonb.result): none | expired | not_confirmed | no_take | capped | conflict | rewarded.
-- Units (10) and the monthly cap (10) are fixed here, not taken from the caller.
create or replace function public.settle_referral_reward(p_referred_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_ref public.referrals%rowtype;
  v_units constant integer := 10;
  v_monthly_cap constant integer := 10;
  v_month_start timestamptz := date_trunc('month', now() at time zone 'Europe/Warsaw') at time zone 'Europe/Warsaw';
  v_rewarded_this_month integer;
  v_left integer;
begin
  if auth.role() is distinct from 'service_role' then
    raise exception 'REFERRAL_FORBIDDEN' using errcode = '42501';
  end if;

  select * into v_ref
  from public.referrals
  where referred_id = p_referred_id
  for update;

  if not found or v_ref.status is distinct from 'pending' then
    return jsonb_build_object('result', 'none');
  end if;

  if v_ref.created_at < now() - interval '90 days' then
    return jsonb_build_object('result', 'expired');
  end if;

  -- Both accounts must have a confirmed e-mail.
  if not exists (select 1 from auth.users u where u.id = v_ref.referred_id and u.email_confirmed_at is not null)
     or not exists (select 1 from auth.users u where u.id = v_ref.referrer_id and u.email_confirmed_at is not null) then
    return jsonb_build_object('result', 'not_confirmed');
  end if;

  -- First finished recording of the referred account (not an imported stem).
  if not exists (
    select 1 from public.takes t
     where t.owner_id = v_ref.referred_id
       and t.status = 'READY'
       and t.is_stem is not true
  ) then
    return jsonb_build_object('result', 'no_take');
  end if;

  -- Monthly cap per referrer; serialized per referrer.
  perform pg_advisory_xact_lock(hashtextextended('referral_reward:' || v_ref.referrer_id::text, 0));
  select count(*)::integer into v_rewarded_this_month
  from public.referrals r
  where r.referrer_id = v_ref.referrer_id
    and r.status = 'rewarded'
    and r.rewarded_at >= v_month_start;
  if v_rewarded_this_month >= v_monthly_cap then
    return jsonb_build_object('result', 'capped');
  end if;

  begin
    -- Same balance + insert path as grant_p24_quota_pack (kind 'take').
    insert into public.studio_quota_credits (user_id, kind, remaining)
    values (v_ref.referrer_id, 'take', v_units)
    on conflict (user_id, kind) do update
      set remaining = public.studio_quota_credits.remaining + excluded.remaining
      where public.studio_quota_credits.remaining + excluded.remaining <= 100000
    returning remaining into v_left;
    if v_left is null then
      raise exception 'REFERRAL_CREDIT_CAP';
    end if;

    v_left := null;
    insert into public.studio_quota_credits (user_id, kind, remaining)
    values (v_ref.referred_id, 'take', v_units)
    on conflict (user_id, kind) do update
      set remaining = public.studio_quota_credits.remaining + excluded.remaining
      where public.studio_quota_credits.remaining + excluded.remaining <= 100000
    returning remaining into v_left;
    if v_left is null then
      raise exception 'REFERRAL_CREDIT_CAP';
    end if;

    update public.referrals
       set status = 'rewarded',
           rewarded_at = now()
     where id = v_ref.id;
  exception
    when others then
      -- The block is rolled back: no half reward.
      return jsonb_build_object('result', 'conflict');
  end;

  return jsonb_build_object(
    'result', 'rewarded',
    'referral_id', v_ref.id,
    'referrer_id', v_ref.referrer_id,
    'units', v_units
  );
end;
$$;

revoke all on function public.settle_referral_reward(uuid) from public, anon, authenticated;
grant execute on function public.settle_referral_reward(uuid) to service_role;
