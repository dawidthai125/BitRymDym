-- Stable catalog numbers for samples (owner decision 2026-11-21).
-- The catalog (/sampel) showed "#NN" computed from list position, so numbers moved
-- when a sample was added, removed or filtered. Now every sample keeps one number.
--
-- Scope: one global sequence over public.studio_samples (BitRymDym and user samples
-- share it). Numbers never move and are never reused; gaps are expected (private,
-- rejected or removed samples keep their number off the public list).
--
-- Additive only. Existing rows are backfilled in creation order (created_at, id),
-- new rows get the next identity value on insert.

-- Supabase runs each migration in one transaction; the lock holds until it commits.
-- Block inserts while we backfill and attach the identity, so no row is missed.
set local lock_timeout = '5s';
lock table public.studio_samples in access exclusive mode;

alter table public.studio_samples
  add column if not exists sample_number integer;

with ordered as (
  select id, row_number() over (order by created_at asc, id asc) as n
  from public.studio_samples
  where sample_number is null
)
update public.studio_samples s
set sample_number = ordered.n + coalesce(
  (select max(sample_number) from public.studio_samples where sample_number is not null),
  0
)
from ordered
where s.id = ordered.id;

-- Identity requires NOT NULL first.
alter table public.studio_samples
  alter column sample_number set not null;

do $$
begin
  if not exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'studio_samples'
      and column_name = 'sample_number'
      and is_identity = 'YES'
  ) then
    alter table public.studio_samples
      alter column sample_number add generated by default as identity;
  end if;
end
$$;

-- Continue the sequence after the backfilled numbers.
select setval(
  pg_get_serial_sequence('public.studio_samples', 'sample_number'),
  greatest(coalesce((select max(sample_number) from public.studio_samples), 0), 1),
  coalesce((select max(sample_number) from public.studio_samples), 0) > 0
);

create unique index if not exists studio_samples_sample_number_uidx
  on public.studio_samples (sample_number);

comment on column public.studio_samples.sample_number is
  'Stable catalog number (#NN). Global identity, backfilled by (created_at, id); never reused.';
