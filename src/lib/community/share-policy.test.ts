import { describe, expect, it } from "vitest";

import { ANONYMIZED_PUBLIC_AUTHOR } from "@/lib/auth/display-name";
import { readFileSync } from "node:fs";
import { join } from "node:path";

import {
  catalogSampleNumbers,
  canCommentPublic,
  canRatePublic,
  parseCatalogSource,
  PLATFORM_AUTHOR,
  publicAuthorName,
} from "@/lib/community/share-policy";

describe("public share gate", () => {
  it("rates only a published public listing and comments only when the author allows them", () => {
    expect(canRatePublic({ published: true, listed: true })).toBe(true);
    expect(canRatePublic({ published: true, listed: false })).toBe(false);
    expect(canRatePublic({ published: false, listed: true })).toBe(false);
    expect(canCommentPublic({ published: true, listed: true, allowComments: true })).toBe(true);
    expect(canCommentPublic({ published: true, listed: true, allowComments: false })).toBe(false);
    expect(canCommentPublic({ published: true, listed: false, allowComments: true })).toBe(false);
  });

  it("always has an author name", () => {
    expect(publicAuthorName({ ownership: "PLATFORM", producer: null })).toBe(PLATFORM_AUTHOR);
    expect(publicAuthorName({ ownership: "PLATFORM", producer: "Redakcja" })).toBe("Redakcja");
    expect(publicAuthorName({ ownership: "USER", displayName: "Mira", producer: "Stare" })).toBe("Mira");
    expect(publicAuthorName({ ownership: "USER", displayName: "  ", producer: null })).toBe(ANONYMIZED_PUBLIC_AUTHOR);
  });
});

describe("sample catalog tab", () => {
  it("opens the official BitRymDym tab by default and keeps an explicit choice", () => {
    expect(parseCatalogSource(undefined)).toBe("brd");
    expect(parseCatalogSource(null)).toBe("brd");
    expect(parseCatalogSource("")).toBe("brd");
    expect(parseCatalogSource("cos")).toBe("brd");
    expect(parseCatalogSource("brd")).toBe("brd");
    expect(parseCatalogSource("user")).toBe("user");
    expect(parseCatalogSource(["user", "brd"])).toBe("user");
  });

  it("uses the parser on /sampel and links the shelf and footer to the BitRymDym tab", () => {
    const read = (path: string) => readFileSync(join(process.cwd(), path), "utf8");
    expect(read("src/app/sampel/page.tsx")).toContain("parseCatalogSource(params.zrodlo)");
    expect(read("src/components/community/community-shelf.tsx")).toContain('href: "/sampel?zrodlo=brd"');
    expect(read("src/components/site/site-footer.tsx")).toContain('href="/sampel?zrodlo=brd"');
  });
});

describe("stable sample numbers", () => {
  it("shows the stored number, whatever the order, filter or newer samples", () => {
    const samples = [
      { id: "c", sampleNumber: 41, createdAt: "2026-11-03T00:00:00Z" },
      { id: "a", sampleNumber: 7, createdAt: "2026-11-01T00:00:00Z" },
    ];
    const before = catalogSampleNumbers(samples);
    expect(before.get("a")).toBe(7);
    expect(before.get("c")).toBe(41);
    const after = catalogSampleNumbers([
      { id: "new", sampleNumber: 42, createdAt: "2026-11-04T00:00:00Z" },
      ...[...samples].reverse(),
    ]);
    expect(after.get("a")).toBe(7);
    expect(after.get("c")).toBe(41);
    expect(after.get("new")).toBe(42);
    expect(catalogSampleNumbers([samples[0]]).get("c")).toBe(41);
  });

  it("falls back to creation order (oldest = 1) before the column exists", () => {
    const numbers = catalogSampleNumbers([
      { id: "b", sampleNumber: null, createdAt: "2026-11-02T00:00:00Z" },
      { id: "a", createdAt: "2026-11-01T00:00:00Z" },
    ]);
    expect(numbers.get("a")).toBe(1);
    expect(numbers.get("b")).toBe(2);
  });

  it("backfills by (created_at, id) and continues with an identity sequence", () => {
    const sql = readFileSync(
      join(process.cwd(), "supabase/migrations/20261121170000_studio_samples_sample_number.sql"),
      "utf8",
    );
    expect(sql).toContain("add column if not exists sample_number integer");
    expect(sql).toContain("order by created_at asc, id asc");
    expect(sql).toContain("add generated by default as identity");
    expect(sql).toContain("setval(");
    expect(sql).toContain("alter column sample_number set not null");
    expect(sql).toContain("unique index if not exists studio_samples_sample_number_uidx");
  });
});
